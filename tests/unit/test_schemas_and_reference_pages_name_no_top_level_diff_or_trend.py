"""The schemas and generated pages name ``ash results diff`` and ``ash results trend``.

``diff`` and ``trend`` are commands of ``ash results``. They never had a top-level
spelling, so ``ash diff`` and ``ash trend`` answer with a usage error. The rows of
tests/unit/cli/test_legacy_spellings_warn_once.py hold that, and hold the markdown the
package ships to the same rule.

Why this file exists
--------------------
The ``history`` section of the configuration was described as a record of each scan
"for ``ash trend``". A generator copies that sentence from the model into the JSON
schemas and into the configuration reference page, so a reader who looked the command
up there was sent to a spelling that does not run. Nothing read the schemas or the
generated pages for a command name, so the sentence stayed in all of them.

What is read
------------
* every string in the JSON schemas ASH publishes (automated_security_helper/schemas);
* every reference page a generator writes (docs/content/reference, the pages whose
  header says "Generated by scripts/"). The CLI page lists the help text of each
  command and option, so a help text that names a top-level spelling shows up there.

What is not read
----------------
* module docstrings and code comments, which are for the people who change the code;
* the hand-written pages, which tests/unit/test_docs_no_legacy_spellings.py reads (the
  page that moves a reader to the new spellings names the old ones on purpose);
* the MCP tool descriptions, which are read by
  tests/unit/cli/mcp/test_a_tool_description_names_the_current_command_spellings.py
"""

from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any, Iterator

import pytest

pytestmark = pytest.mark.unit

REPO_ROOT = Path(__file__).resolve().parents[2]

#: ``ash`` or ``ashv3`` as a word of its own, with an optional ``./``, then ``diff`` or
#: ``trend`` as a word of its own. Not ``ash results diff``, ``bash diff``, ``ash
#: difference`` or ``ash trendy``. It is the pattern the markdown check of
#: tests/unit/cli/test_legacy_spellings_warn_once.py uses.
TOP_LEVEL = re.compile(r"(?<![\w./-])(?:\./)?(?:ash|ashv3) (?:diff|trend)\b")

#: What a page a generator writes says in its first lines.
GENERATED_BANNER = "Generated by scripts/"

#: The pages that carry it today, one for each reference generator. The read finds a
#: page by its banner, so a page that lost the banner would drop out of it unseen; a
#: row holds this list against what the read finds.
GENERATED_PAGES = frozenset(
    {
        "cli.md",
        "configuration.md",
        "converters.md",
        "environment-variables.md",
        "mcp-tools.md",
        "reporters.md",
        "scanner-facets.md",
        "scanners.md",
    }
)


def _strings(node: Any, pointer: str = "") -> Iterator[tuple[str, str]]:
    """Every string in a parsed JSON document, with the pointer to it."""
    if isinstance(node, str):
        yield pointer, node
    elif isinstance(node, dict):
        for key, value in node.items():
            yield from _strings(value, f"{pointer}/{key}")
    elif isinstance(node, list):
        for index, value in enumerate(node):
            yield from _strings(value, f"{pointer}/{index}")


def schema_hits(root: Path = REPO_ROOT) -> list[str]:
    """``file/pointer: text`` for each schema string that names a top-level spelling."""
    schemas = root / "automated_security_helper" / "schemas"
    hits: list[str] = []
    for path in sorted(schemas.glob("*.json")):
        document = json.loads(path.read_text(encoding="utf-8"))
        hits += [
            f"{path.name}{pointer}: {text}"
            for pointer, text in _strings(document)
            if TOP_LEVEL.search(text)
        ]
    return hits


def generated_pages(root: Path = REPO_ROOT) -> dict[str, str]:
    """The reference pages a generator writes, by file name."""
    pages: dict[str, str] = {}
    for path in sorted((root / "docs" / "content" / "reference").glob("*.md")):
        text = path.read_text(encoding="utf-8")
        if GENERATED_BANNER in "\n".join(text.splitlines()[:3]):
            pages[path.name] = text
    return pages


def page_hits(root: Path = REPO_ROOT) -> list[str]:
    """``page:line: text`` for each line of a generated page that names one."""
    return [
        f"{name}:{number}: {line.strip()}"
        for name, text in generated_pages(root).items()
        for number, line in enumerate(text.splitlines(), start=1)
        if TOP_LEVEL.search(line)
    ]


def test_the_published_schemas_name_no_top_level_diff_or_trend() -> None:
    assert schema_hits() == []


def test_the_generated_reference_pages_name_no_top_level_diff_or_trend() -> None:
    assert page_hits() == []


def test_the_read_finds_a_page_for_each_reference_generator() -> None:
    """A page that stops opening with the banner fails here, not by passing unread."""
    assert GENERATED_PAGES <= set(generated_pages())


@pytest.mark.parametrize(
    ("text", "flagged"),
    [
        ("Run history: a record of each scan, for ``ash trend``.", True),
        ("Compare two files with `ash diff`.", True),
        ("Run ashv3 trend over the saved runs.", True),
        ("./ash diff before.json after.json", True),
        ("A record of each scan, for ``ash results trend``.", False),
        ("Compare two files with `ash results diff`.", False),
        ("bash diff before.txt after.txt", False),
        ("The ash difference between two runs.", False),
        ("An ash trendy name.", False),
        ("Read ./ash.yaml trend settings.", False),
    ],
)
def test_the_pattern_tells_a_top_level_spelling_from_the_results_one(
    text: str, flagged: bool
) -> None:
    assert bool(TOP_LEVEL.search(text)) is flagged


def test_a_schema_string_that_names_ash_trend_is_reported(tmp_path: Path) -> None:
    schemas = tmp_path / "automated_security_helper" / "schemas"
    schemas.mkdir(parents=True)
    planted = {
        "$defs": {"History": {"description": "A record for ``ash trend``."}},
        "examples": ["ash results trend"],
    }
    (schemas / "Planted.json").write_text(json.dumps(planted), encoding="utf-8")
    assert schema_hits(tmp_path) == [
        "Planted.json/$defs/History/description: A record for ``ash trend``."
    ]


def test_a_generated_page_that_names_ash_diff_is_reported_and_a_written_one_is_not(
    tmp_path: Path,
) -> None:
    reference = tmp_path / "docs" / "content" / "reference"
    reference.mkdir(parents=True)
    generated = "<!--\n  Generated by scripts/generate_planted.py.\n-->\n"
    (reference / "planted.md").write_text(
        generated + "\nRun `ash diff` first.\nRun `ash results diff` next.\n",
        encoding="utf-8",
    )
    (reference / "by-hand.md").write_text(
        "The old spelling was `ash diff`.\n", encoding="utf-8"
    )
    assert page_hits(tmp_path) == ["planted.md:5: Run `ash diff` first."]
