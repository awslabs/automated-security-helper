"""The documented MCP tool surface and the registered one must be the same set.

WHY THIS EXISTS
---------------
ASH shipped four source-delivery tools that no client could call. The
implementation was written, hardened against zip traversal and git argument
injection, covered by 40 unit tests, and documented with worked examples --
and none of that caught the fact that `@mcp.tool()` was never applied, so
`tools/list` did not return them. Every individual artifact was correct. Only
the connection between them was missing, and nothing tested the connection.

That is the failure this module exists to make loud. A test that exercises a
tool function directly cannot see whether the tool is reachable over the
protocol, and a doc example cannot either. The only way to catch it is to
compare the two surfaces against each other, which is what happens below.

HOW THE TWO SIDES ARE DERIVED
-----------------------------
Deliberately from different places, because deriving both from the same source
would make the comparison vacuous:

* Registered: `await mcp.list_tools()` on the real server object. Not a regex
  over the source -- the runtime answer, the same one a client gets.
* Documented: the places the docs declare that a tool exists. That is the tool
  sections of the MCP tools reference, `docs/content/reference/mcp-tools.md`,
  one `## <name>` heading per tool, plus two spellings anywhere in README or
  `docs/`: a link to a tool's section of that page (`mcp-tools.md#<name>`) and
  the `mcp__ash__<name>` client-facing spelling. The reverse direction uses bare
  tool names appearing anywhere in the docs tree or README.

The reference page is generated from the registry by
`scripts/generate_mcp_tool_reference.py`, which looks like the vacuous case. It
is not one. The page is committed, so it matches the registry only if someone
ran the generator after the last tool change. And this module reads the page's
headings, not the generator's output: the generator's `--check`, which
`tests/unit/test_generated_docs_freshness.py` runs, compares the page with what
the generator renders today, so a generator that dropped or renamed a tool would
pass it while failing here.

The prose pages name tools as bare code spans (`run_ash_scan`), and those cannot
be the documented side. A code span is as often a parameter, a result field or a
Python function as a tool: when this was written, the agent steering guide alone
had 84 distinct identifier-shaped code spans that are not tool names. So a prose
page that names a tool which does not exist is caught here only when it links
to the tool's section or uses the namespaced spelling.

The forward direction (documented implies registered) is the one that had
already broken. The reverse (registered implies documented) catches a tool added
without a mention anywhere, which is how a surface silently grows.

WHAT THIS DOES NOT CHECK
------------------------
Signatures. A tool whose documented arguments no longer match its registered
ones passes here. Names are what broke, so names are what this pins; argument
drift would need the schema compared against the examples, which is a bigger
job and a separate test.

Nor the wire. `mcp.list_tools()` is the in-process registration table, one Python
call from the decorator that filled it, so everything between that table and a
real client is out of scope here: the console-script entry point, the stdio
transport, the `initialize` exchange, and the serialization of each signature
into JSON Schema. `.github/actions/validate-mcp/compare_tool_surface.py` covers
that half -- it drives `ash mcp` through the MCP Inspector as a client would and
diffs the full `tools/list` reply, schemas included, against a committed golden.
The two overlap on exactly one property, the set of names, and neither subsumes
the other: this module can run in a unit test suite with no Node toolchain, and
that one can see a tool that is registered but unreachable.

`scripts/verify_docs_freshness.py` compares tool names against the docs as well.
It reads the registered side from a parse of the `@mcp.tool` decorators in
`mcp_server.py`, so it can run in the lint job without importing the package.
This module uses the live registry instead, which is the answer a client gets.
"""

from __future__ import annotations

import re
from pathlib import Path
from typing import Set

import pytest

REPO_ROOT = Path(__file__).resolve().parents[4]
DOCS_DIR = REPO_ROOT / "docs"
README = REPO_ROOT / "README.md"

# The published tool inventory, generated by scripts/generate_mcp_tool_reference.py.
# A section on it naming a tool that does not exist is a promise to a reader that
# nothing keeps.
REFERENCE_PAGE = DOCS_DIR / "content" / "reference" / "mcp-tools.md"

# The client-facing spelling. MCP clients namespace a server's tools, so a tool
# registered as `set_source_git` is called as `mcp__ash__set_source_git`. The docs
# used it in examples; none do today, and an example that does is a direct
# instruction to call the tool, so it is still read.
MCP_TOOL_REFERENCE = re.compile(r"mcp__ash__([a-z_][a-z0-9_]*)")

# A tool's section of the reference page: the `## <name>` heading the generator
# writes for each registered tool. The page's other sections (`## Resources`,
# `## Severity levels`) are capitalized prose and do not match.
#
# This replaces the regex for a row of README's old MCP tools table, and the row
# regex could not simply be pointed at the new page: the page's parameter tables
# use the same row shape (`| `source_dir` | string | ...`), so it would have read
# every parameter as a tool.
REFERENCE_PAGE_TOOL_SECTION = re.compile(
    r"^##[ \t]+([a-z_][a-z0-9_]*)[ \t]*$", re.MULTILINE
)

# A link from another page to a tool's section of the reference page, such as
# `[`resolve_ash_workspace`](../reference/mcp-tools.md#resolve_ash_workspace)`. The
# anchor is the heading's slug, which for a snake_case name is the name itself.
TOOL_SECTION_LINK = re.compile(r"mcp-tools\.md#([a-z_][a-z0-9_]*)")

# Floor for the reference page's own sections, and the same number as the
# registered side's floor below: the page has to list every registered tool, so it
# cannot honestly list fewer than the server is required to register.
MINIMUM_REFERENCE_PAGE_TOOLS = 14

# Names the docs may mention without a matching registered tool.
#
# This list is the escape hatch for prose that deliberately refers to a tool
# that does not exist yet. It must stay empty or near-empty, and every entry
# needs a reason -- an entry is a promise to a reader that something exists, so
# it should cost something to add. An entry is only legitimate when the docs say
# plainly that the tool is unavailable; naming it as though it works is the
# defect this module exists to catch, not something to exempt.
# ``select_profile`` was exempted here, on the grounds that registering a tool
# which binds a config nothing reads would publish a call returning success and
# changing nothing. The exemption is gone because the condition it named is gone:
# ``bind_session_config`` now records a path materialized into the session
# sandbox, ``resolve_session_config_path`` reads it, and ``run_ash_scan`` plus both
# workspace tools pass it to the scan. ``ash mcp --profile`` populates the
# registry, without which nothing could be selected in the first place.
DOCUMENTED_BUT_NOT_REGISTERED_EXEMPTIONS: dict[str, str] = {}

# Registered tools that need no prose mention.
#
# Same discipline in the other direction. Empty by design.
REGISTERED_BUT_NOT_DOCUMENTED_EXEMPTIONS: dict[str, str] = {}


def _iter_doc_files():
    """Yield every markdown file the documented surface may be declared in."""
    if README.is_file():
        yield README
    yield from sorted(DOCS_DIR.rglob("*.md"))


def _tool_names_declared_in(text: str, *, reference_page: bool = False) -> Set[str]:
    """Return every tool `text` declares, in each spelling the docs use for one.

    Section headings count only on the reference page; a `## lowercase` heading on
    any other page is not a claim that a tool exists.
    """
    found = set(MCP_TOOL_REFERENCE.findall(text))
    found.update(TOOL_SECTION_LINK.findall(text))
    if reference_page:
        found.update(REFERENCE_PAGE_TOOL_SECTION.findall(text))
    return found


def _documented_tool_names() -> Set[str]:
    """Return every tool the docs declare: reference-page sections, links, mcp__ash__."""
    found: Set[str] = set()
    for path in _iter_doc_files():
        found.update(
            _tool_names_declared_in(
                path.read_text(encoding="utf-8"),
                reference_page=path == REFERENCE_PAGE,
            )
        )
    return found


def _reference_page_tool_names() -> Set[str]:
    """Return the tools the reference page has a section for."""
    if not REFERENCE_PAGE.is_file():
        pytest.fail(
            f"{REFERENCE_PAGE.relative_to(REPO_ROOT)} does not exist. If the MCP tools "
            "reference moved, point REFERENCE_PAGE at its new path; without it the "
            "published tool inventory is compared against nothing."
        )
    return set(
        REFERENCE_PAGE_TOOL_SECTION.findall(REFERENCE_PAGE.read_text(encoding="utf-8"))
    )


def _docs_corpus() -> str:
    """Return the concatenated docs text, for the bare-name reverse check."""
    return "\n".join(path.read_text(encoding="utf-8") for path in _iter_doc_files())


async def _registered_tool_names() -> Set[str]:
    """Return the tool names the running server actually exposes.

    Uses the server object rather than parsing the source, so this is the set a
    client receives from `tools/list` -- the thing that was wrong.
    """
    from automated_security_helper.cli.mcp_server import mcp

    return {tool.name for tool in await mcp.list_tools()}


def test_docs_declare_at_least_one_tool() -> None:
    """Guard the guard: an empty documented set would make the rest vacuous.

    If a regex stops matching -- the docs switch spelling, the generator changes
    its headings, the paths move -- every set comparison below would trivially
    pass. This is the canary for that, and it is why the forward test can be
    trusted when it is green.

    It has two halves, because a floor on the documented set cannot control every
    spelling in it. This canary used to require five `mcp__ash__` names in the docs;
    the rewritten docs use that spelling nowhere, and the forward test went on
    passing over an empty set while this one failed. Today the reference page's
    sections supply nearly the whole set, so a floor on the total would stay green
    with the link or `mcp__ash__` regex matching nothing.

    * The tree: the reference page must have at least as many tool sections as the
      registered side's floor, and the walk the forward test uses must reach them.
      The sections are generator output, so this does not depend on how any page is
      worded.
    * Each spelling, on a sample written the way the docs write it, through the
      same extraction the walk applies to every file. The links and the
      `mcp__ash__` spelling are prose choices with few or no uses in the tree, so
      their control cannot be a count of the tree.
    """
    sections = _reference_page_tool_names()
    assert len(sections) >= MINIMUM_REFERENCE_PAGE_TOOLS, (
        f"{REFERENCE_PAGE.relative_to(REPO_ROOT)} has {len(sections)} tool "
        f"section(s), below the floor of {MINIMUM_REFERENCE_PAGE_TOOLS}: "
        f"{sorted(sections)}. If the generator changed how it writes a tool's "
        "heading, fix REFERENCE_PAGE_TOOL_SECTION -- do not delete this assertion, "
        "or the parity checks below stop meaning anything."
    )

    missed = sections - _documented_tool_names()
    assert not missed, (
        f"The walk the forward test uses does not read the reference page's sections "
        f"{sorted(missed)}, so the forward test is not checking them. Check that "
        "_iter_doc_files still yields REFERENCE_PAGE under the same path."
    )

    samples = [
        # How scripts/generate_mcp_tool_reference.py opens a tool's section.
        ("## run_ash_scan\n\nStarts a scan asynchronously.\n", True, "run_ash_scan"),
        # How a how-to page links to one.
        (
            (
                "- [`resolve_ash_workspace`]"
                "(../reference/mcp-tools.md#resolve_ash_workspace) returns the plan,"
            ),
            False,
            "resolve_ash_workspace",
        ),
        # How an MCP client example names one.
        ("Call `mcp__ash__set_source_git` with the URL.", False, "set_source_git"),
    ]
    for text, reference_page, expected in samples:
        found = _tool_names_declared_in(text, reference_page=reference_page)
        assert found == {expected}, (
            f"Read {sorted(found)} from {text!r}, expected exactly {{{expected!r}}}. "
            "One of the spellings this module reads no longer matches the way the docs "
            "write it; fix its regex, and keep this sample in step with the docs."
        )


@pytest.mark.asyncio
async def test_server_registers_at_least_the_known_tools() -> None:
    """Guard the other side: an empty registered set would also be vacuous."""
    registered = await _registered_tool_names()
    assert len(registered) >= 14, (
        f"Only {len(registered)} tools registered: {sorted(registered)}. The "
        "server should expose at least the original 14."
    )


@pytest.mark.asyncio
async def test_every_documented_tool_is_registered() -> None:
    """A tool the docs tell clients to call must be callable.

    This is the assertion that would have caught the source-delivery gap: the
    docs published `mcp__ash__set_source_git` and friends while `tools/list`
    returned 14 names that did not include them.
    """
    documented = _documented_tool_names()
    registered = await _registered_tool_names()

    missing = documented - registered - set(DOCUMENTED_BUT_NOT_REGISTERED_EXEMPTIONS)
    assert not missing, (
        "These tools are documented but not registered with @mcp.tool(), so no "
        f"client can call them: {sorted(missing)}.\n"
        "Either register them in automated_security_helper/cli/mcp_server.py, "
        "remove the claim from the docs (a section of the MCP tools reference is "
        "removed by regenerating it with scripts/generate_mcp_tool_reference.py), "
        "or -- if the reference is deliberately aspirational -- add the name to "
        "DOCUMENTED_BUT_NOT_REGISTERED_EXEMPTIONS with a reason."
    )


@pytest.mark.asyncio
async def test_every_registered_tool_is_mentioned_in_the_docs() -> None:
    """A tool clients can call should be findable in the docs.

    Looser than the forward direction on purpose: this matches the bare tool
    name anywhere in the docs tree or README, because that is how the prose pages
    name tools. A bare name cannot say what it refers to, which is why it is not
    used for the forward direction, but its presence is enough to say a reader
    can find the tool.

    The reference page names every tool it has a section for, so since that page
    became generated this direction fails only when the page is stale, which
    test_reference_page_lists_exactly_the_registered_tools below also reports. It
    does not check that any hand-written page mentions a tool: a tool documented
    only by its generated section passes.
    """
    registered = await _registered_tool_names()
    corpus = _docs_corpus()

    undocumented = {
        name
        for name in registered
        if name not in corpus and name not in REGISTERED_BUT_NOT_DOCUMENTED_EXEMPTIONS
    }
    assert not undocumented, (
        f"These tools are registered but appear nowhere in the docs: "
        f"{sorted(undocumented)}.\n"
        "Regenerate the MCP tools reference with "
        "`uv run python scripts/generate_mcp_tool_reference.py` and mention them in "
        "the relevant guide, or add the name to "
        "REGISTERED_BUT_NOT_DOCUMENTED_EXEMPTIONS with a reason."
    )


@pytest.mark.asyncio
async def test_reference_page_lists_exactly_the_registered_tools() -> None:
    """The MCP tools reference is the inventory, so it must match the inventory.

    Both directions in one assertion because both had drifted when the inventory
    was a table in README: it named `scan_directory` and
    `scan_directory_with_progress`, neither of which is a registered tool, while
    `list_scanners`, `validate_config` and `list_profiles` were registered and
    absent from it. A reader who trusts the inventory would have called two tools
    that do not exist and never learned about three that do.

    The inventory is now docs/content/reference/mcp-tools.md, one section per
    tool. The module docstring explains why comparing a page generated from the
    registry against the registry still tests something.
    """
    registered = await _registered_tool_names()
    sections = _reference_page_tool_names()
    page = REFERENCE_PAGE.relative_to(REPO_ROOT)

    ghosts = sections - registered
    absent = registered - sections - set(REGISTERED_BUT_NOT_DOCUMENTED_EXEMPTIONS)

    assert not ghosts, (
        f"{page} has sections for tools that are not registered: {sorted(ghosts)}. "
        "Regenerate it with `uv run python scripts/generate_mcp_tool_reference.py`, "
        "or register the tools."
    )
    assert not absent, (
        f"These registered tools have no section in {page}: {sorted(absent)}. "
        "Regenerate it with `uv run python scripts/generate_mcp_tool_reference.py`; "
        "if they are still missing afterwards, the generator is dropping them."
    )


@pytest.mark.asyncio
async def test_exemptions_are_not_stale() -> None:
    """An exemption that no longer applies has to be removed.

    Otherwise the lists rot into a permanent allowlist and the gate quietly
    weakens: a name left in DOCUMENTED_BUT_NOT_REGISTERED_EXEMPTIONS after the
    tool is registered would keep suppressing a check that now passes anyway.
    """
    documented = _documented_tool_names()
    registered = await _registered_tool_names()

    for name in DOCUMENTED_BUT_NOT_REGISTERED_EXEMPTIONS:
        assert name in documented, (
            f"{name!r} is exempted as documented-but-not-registered, but the "
            "docs no longer mention it. Remove the exemption."
        )
        assert name not in registered, (
            f"{name!r} is exempted as documented-but-not-registered, but it is "
            "now registered. Remove the exemption."
        )

    for name in REGISTERED_BUT_NOT_DOCUMENTED_EXEMPTIONS:
        assert name in registered, (
            f"{name!r} is exempted as registered-but-not-documented, but it is "
            "no longer registered. Remove the exemption."
        )
        assert name not in _docs_corpus(), (
            f"{name!r} is exempted as registered-but-not-documented, but the "
            "docs now mention it. Remove the exemption."
        )
