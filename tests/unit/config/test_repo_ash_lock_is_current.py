"""This repository's own ``.ash.lock`` covers every symbol suppression and is current.

Why this exists
---------------
The repository's configs carry symbol-scoped suppressions, so a scan of it
refuses them unless each file has a lock entry, and applies them only while the
file hashes to that entry. A change to a locked file therefore fails here until
the change is reviewed and ``ash suppress refresh <file>`` records it, the same
check ``ash suppress verify`` gives CI. The lock was generated by running
``ash suppress add`` over the existing entries.
"""

from __future__ import annotations

from pathlib import Path

import pytest
import yaml

from automated_security_helper.utils.ash_lock import AshLock, lock_key

pytestmark = pytest.mark.unit

REPO = Path(__file__).resolve().parents[3]
CONFIGS = (".ash.yaml", ".ash/.ash_alpha_plugins.yaml")


def _symbol_entries():
    for name in CONFIGS:
        data = yaml.safe_load((REPO / name).read_text(encoding="utf-8"))
        for entry in data["global_settings"]["suppressions"]:
            if entry.get("symbol"):
                yield name, entry


def test_every_symbol_suppression_of_our_configs_has_a_lock_entry():
    lock = AshLock.load(REPO)
    entries = list(_symbol_entries())
    assert entries, "the configs hold no symbol suppression to lock"
    for name, entry in entries:
        key = lock_key(entry["path"])
        assert key in lock.entries, f"{name}: {entry['path']} is not locked"
        scope = (entry["rule_id"], entry["symbol"])
        assert scope in {(s.rule_id, s.symbol) for s in lock.entries[key].scopes}, (
            f"{name}: {entry['rule_id']} in {entry['symbol']} is not recorded for {key}"
        )


def test_the_lock_is_current():
    problems = AshLock.load(REPO).problems()
    assert not problems, (
        f"{problems}: review the change, then run `ash suppress refresh <file>`"
    )


def test_the_lock_holds_nothing_our_configs_do_not_use():
    used = {lock_key(e["path"]) for _, e in _symbol_entries()}
    assert set(AshLock.load(REPO).entries) == used
