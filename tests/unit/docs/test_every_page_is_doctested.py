PIN_PRIMITIVES = ("assert_on_page", "_page_text", "_page_section")
#: Where a journey twin lives, by file name.
TWIN_GLOBS = ("test_*twin*.py", "test_*journey*.py")
#: What the allowlist's header must keep saying.
RATCHET_SENTENCE = "may only shrink"

