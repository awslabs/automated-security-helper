PLANTED = "planted/new-page.md"


def test_a_page_with_no_mechanism_and_no_allowlist_entry_fails_the_ratchet():
    pages = {"a.md", PLANTED}
    coverage = {"a.md": {f"{CLAIMS}: test_page_claims.py"}}

    failures = ratchet_failures(pages, coverage, [])

    assert len(failures) == 1
    assert PLANTED in failures[0] and "no doctest mechanism" in failures[0]


def test_an_allowlisted_page_passes_until_it_gains_a_mechanism():
    pages = {"a.md", PLANTED}

    assert ratchet_failures(pages, {"a.md": {"x"}}, [PLANTED]) == []

    stale = ratchet_failures(pages, {"a.md": {"x"}, PLANTED: {"y"}}, [PLANTED])
    assert len(stale) == 1 and "Delete its line" in stale[0]


def test_an_allowlist_entry_for_a_page_that_is_gone_or_out_of_order_fails():
    pages = {"a.md", "b.md"}
    coverage: Coverage = {}

    gone = ratchet_failures(pages, coverage, ["a.md", "b.md", "c.md"])
    assert any("c.md" in f and "not a page" in f for f in gone)

    unsorted = ratchet_failures(pages, coverage, ["b.md", "a.md"])
    assert any("not sorted" in f for f in unsorted)


def test_a_page_in_the_tree_and_not_the_nav_fails_the_reconcile_and_so_does_the_reverse():
    failures = reconcile_failures(
        {"a.md", "b.md"}, {"a.md", "c.md"}, ["nav:1: no page"]
    )

    assert any("b.md" in f and "no .nav.yml entry" in f for f in failures)
    assert any("c.md" in f and "not a file" in f for f in failures)
    assert any("no page" in f for f in failures)
    assert reconcile_failures({"a.md"}, {"a.md"}) == []


