def _as_page(text: str, pages: set[str]) -> str | None:
    """``text`` as a page of ``pages``: the path under docs/content, with or without that
    prefix, and without a ``#anchor``."""
    text = text.partition("#")[0].removeprefix("docs/content/")
    return text if text in pages else None


def _strings_in(node: ast.AST) -> Iterator[str]:
    for sub in ast.walk(node):
        if isinstance(sub, ast.Constant) and isinstance(sub.value, str):
            yield sub.value


def _flatten_division(
    node: ast.AST, parts: list[str | None], bases: dict[str, str]
) -> None:
    if isinstance(node, ast.BinOp) and isinstance(node.op, ast.Div):
        _flatten_division(node.left, parts, bases)
        _flatten_division(node.right, parts, bases)
    elif isinstance(node, ast.Constant) and isinstance(node.value, str):
        parts.append(node.value)
    elif isinstance(node, ast.Name) and node.id in bases:
        parts.append(bases[node.id])
    else:
        parts.append(None)


def _built_path(node: ast.AST, bases: dict[str, str]) -> str | None:
    """The path ``node`` builds from string literals, or None when it builds none.

    ``base / "a" / "b.md"`` is the trailing run of literals joined with ``/``, where a
    ``base`` that is a module-level path built the same way counts as a literal (so
    ``PAGES_DIR / "a.md"`` is ``docs/content/a.md`` when ``PAGES_DIR`` is
    ``REPO_ROOT / "docs" / "content"``), and any other base ends the run.
    ``Path("a", "b.md")`` is its arguments joined.
    """
    if isinstance(node, ast.BinOp) and isinstance(node.op, ast.Div):
        parts: list[str | None] = []
        _flatten_division(node, parts, bases)
        tail: list[str] = []
        for part in reversed(parts):
            if part is None:
                break
            tail.append(part)
        return "/".join(reversed(tail)) if tail else None
    if isinstance(node, ast.Call) and node.args:
        name = (
            node.func.id
            if isinstance(node.func, ast.Name)
            else getattr(node.func, "attr", "")
        )
        literals = [
            arg.value
            for arg in node.args
            if isinstance(arg, ast.Constant) and isinstance(arg.value, str)
        ]
        if name in ("Path", "PurePath", "PurePosixPath") and len(literals) == len(
            node.args
        ):
            return "/".join(literals)
    return None


def _path_bases(tree: ast.Module) -> dict[str, str]:
    """Module-level ``NAME = <path expression>``: the path each name holds."""
    bases: dict[str, str] = {}
    for stmt in tree.body:
        if (
            isinstance(stmt, ast.Assign)
            and len(stmt.targets) == 1
            and isinstance(stmt.targets[0], ast.Name)
        ):
            built = _built_path(stmt.value, bases)
            if built:
                bases[stmt.targets[0].id] = built
    return bases


def _paths_under_content(node: ast.AST, bases: dict[str, str]) -> Iterator[str]:
    """Every path ``node`` builds that sits under ``docs/content``, as relative to it.

    Only the ``docs/content`` prefix makes a built path a page: ``tmp_path / "index.md"``
    in a test that writes a page of its own names no page of the site.
    """
    for sub in ast.walk(node):
        built = _built_path(sub, bases)
        if built and built.startswith("docs/content/"):
            yield built.removeprefix("docs/content/")


def _page_literals(
    node: ast.AST, constants: dict[str, set[str]], bases: dict[str, str]
) -> set[str]:
    """Every string and built path in ``node``, and what each module-level constant it
    uses holds."""
    found = set(_strings_in(node)) | set(_paths_under_content(node, bases))
    for sub in ast.walk(node):
        if isinstance(sub, ast.Name) and sub.id in constants:
            found |= constants[sub.id]
    return found


def _module_constants(tree: ast.Module, bases: dict[str, str]) -> dict[str, set[str]]:
    """Module-level ``NAME = <expression>``: the strings and paths the expression holds."""
    constants: dict[str, set[str]] = {}
    for stmt in tree.body:
        if isinstance(stmt, ast.Assign):
            names, value = (
                [t for t in stmt.targets if isinstance(t, ast.Name)],
                stmt.value,
            )
        elif isinstance(stmt, ast.AnnAssign) and isinstance(stmt.target, ast.Name):
            names, value = [stmt.target], stmt.value
        else:
            continue
        if value is None:
            continue
        held = set(_strings_in(value)) | set(_paths_under_content(value, bases))
        for name in names:
            constants[name.id] = held
    return constants


def _called_names(node: ast.AST) -> set[str]:
    return {
        sub.func.id
        for sub in ast.walk(node)
        if isinstance(sub, ast.Call) and isinstance(sub.func, ast.Name)
    }


def pages_pinned_by_functions(source: str, pages: set[str]) -> set[str]:
    """The pages a module's page-pinning functions name (mechanism 1, first half).

    A function is pinning when it calls ``assert_on_page``, ``_page_text`` or
    ``_page_section``, or a function of the module that does, however deep.
    """
    tree = ast.parse(source)
    bases = _path_bases(tree)
    constants = _module_constants(tree, bases)
    functions = [
        node
        for node in ast.walk(tree)
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef))
    ]
    pinning = set(PIN_PRIMITIVES)
    grew = True
    while grew:
        grew = False
        for function in functions:
            if function.name not in pinning and _called_names(function) & pinning:
                pinning.add(function.name)
                grew = True
    found: set[str] = set()
    for function in functions:
        if function.name in PIN_PRIMITIVES or function.name not in pinning:
            continue
        found |= _page_literals(function, constants, bases)
    for stmt in tree.body:
        if isinstance(stmt, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            continue
        if _called_names(stmt) & pinning:
            found |= _page_literals(stmt, constants, bases)
    return {page for text in found if (page := _as_page(text, pages))}


def pages_built_as_paths(source: str, pages: set[str]) -> set[str]:
    """The pages a module builds a ``docs/content/...`` path to (the second half of
    mechanism 1)."""
    tree = ast.parse(source)
    found = set(_paths_under_content(tree, _path_bases(tree)))
    return {page for text in found if (page := _as_page(text, pages))}


def pages_named_in(source: str, pages: set[str]) -> set[str]:
    """The pages a module names, as a string equal to a page's path or as a path built
    under ``docs/content`` (mechanism 3).

    A string must hold a ``/``: a bare ``"index.md"`` is as likely a file the module
    writes for itself as the site's front page, and a root page is named by its path
    under ``docs/content``.
    """
    tree = ast.parse(source)
    found = {text for text in _strings_in(tree) if "/" in text}
    found |= set(_paths_under_content(tree, _path_bases(tree)))
    return {page for text in found if (page := _as_page(text, pages))}


