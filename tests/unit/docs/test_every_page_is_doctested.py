def _add(coverage: Coverage, pages: Iterable[str], evidence: str) -> None:
    for page in pages:
        coverage.setdefault(page, set()).add(evidence)


def claims_coverage(pages: set[str]) -> Coverage:
    coverage: Coverage = {}
    for path in sorted(HERE.glob("test_*.py")):
        if path == Path(__file__).resolve():
            continue
        source = path.read_text(encoding="utf-8")
        named = pages_pinned_by_functions(source, pages) | pages_built_as_paths(
            source, pages
        )
        _add(coverage, named, f"{CLAIMS}: {path.name}")
    return coverage


def examples_coverage(pages: set[str]) -> Coverage:
    runner, checks = _runner(), _checks()
    coverage: Coverage = {}
    for page in sorted(pages):
        parsed = checks.parse_page(CONTENT / page, REPO_ROOT)
        if runner.session_blocks(parsed):
            _add(coverage, [page], f"{EXAMPLES}: docs runner runs its blocks")
    return coverage


def twin_coverage(pages: set[str]) -> Coverage:
    coverage: Coverage = {}
    for pattern in TWIN_GLOBS:
        for path in sorted(RUNNER_DIR.glob(pattern)):
            named = pages_named_in(path.read_text(encoding="utf-8"), pages)
            _add(coverage, named, f"{TWIN}: {path.name}")
    return coverage


_BANNER = re.compile(r"\A\s*<!--\s*Generated by (scripts/[\w./-]+\.py) ")


def generator_of(page_text: str) -> str | None:
    """The generator a page's banner names, when it opens with one."""
    match = _BANNER.match(page_text)
    return match.group(1) if match else None


def _freshness_registry() -> dict[str, str]:
    """``REFERENCE_PAGES`` of test_generated_docs_freshness.py: generator -> page name."""
    tree = ast.parse(FRESHNESS_TEST.read_text(encoding="utf-8"))
    for stmt in tree.body:
        if isinstance(stmt, ast.Assign) and any(
            isinstance(t, ast.Name) and t.id == "REFERENCE_PAGES" for t in stmt.targets
        ):
            return ast.literal_eval(stmt.value)
    pytest.fail(
        f"{FRESHNESS_TEST.relative_to(REPO_ROOT)} no longer defines REFERENCE_PAGES, "
        "the table of generated pages under a freshness check. Point this gate at "
        "wherever that table lives now."
    )


def generated_coverage(pages: set[str]) -> Coverage:
    registry = _freshness_registry()
    coverage: Coverage = {}
    for page in sorted(pages):
        generator = generator_of((CONTENT / page).read_text(encoding="utf-8"))
        if generator is None or not (REPO_ROOT / generator).is_file():
            continue
        written = registry.get(Path(generator).name)
        if written is not None and page == f"reference/{written}":
            _add(
                coverage,
                [page],
                f"{GENERATED}: {generator}, checked by {FRESHNESS_TEST.name}",
            )
    return coverage


def coverage_of(pages: set[str]) -> Coverage:
    merged: Coverage = {}
    for part in (
        claims_coverage(pages),
        examples_coverage(pages),
        twin_coverage(pages),
        generated_coverage(pages),
    ):
        for page, evidence in part.items():
            merged.setdefault(page, set()).update(evidence)
    return merged


