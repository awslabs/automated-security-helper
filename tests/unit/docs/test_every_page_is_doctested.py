def _load(name: str, path: Path):
    if name in sys.modules:
        return sys.modules[name]
    if str(REPO_ROOT) not in sys.path:
        sys.path.insert(0, str(REPO_ROOT))
    spec = importlib.util.spec_from_file_location(name, path)
    assert spec and spec.loader
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module
    spec.loader.exec_module(module)
    return module


def _runner():
    """tests/integration/docs/docs_runner.py, loaded the way test_docs_examples.py loads it."""
    return _load("_ash_docs_runner", RUNNER_DIR / "docs_runner.py")


def _checks():
    return _runner().load_docs_checks()


def _site_pages() -> tuple[set[str], set[str], list[str]]:
    """(pages in the tree, pages in the nav, nav entries that name nothing), relative
    to docs/content."""
    checks = _checks()
    site = checks.load_site(str(REPO_ROOT))
    tree = {
        path.resolve().relative_to(site.docs_dir).as_posix()
        for path in checks.listed_files(site.docs_dir, ["**/*.md"])
    }
    reachable, problems = checks.nav_targets(site)
    nav = {path.relative_to(site.docs_dir).as_posix() for path in reachable}
    return tree, nav, [f"{where}:{line}: {text}" for where, line, text in problems]


def reconcile_failures(
    tree: set[str], nav: set[str], unresolved: Iterable[str] = ()
) -> list[str]:
    """What is wrong when the content tree and the navigation list different pages."""
    failures = [
        f"docs/content/{page} is in the content tree but in no .nav.yml entry or glob, so "
        "the gate cannot tell whether the site means it as a page. Add it to "
        "docs/content/.nav.yml (the build fails on a page in no nav)"
        for page in sorted(tree - nav)
    ]
    failures += [
        f"docs/content/{page} is in the navigation but is not a file in the content tree"
        for page in sorted(nav - tree)
    ]
    failures += [f"nav entry names no page: {problem}" for problem in unresolved]
    return failures


