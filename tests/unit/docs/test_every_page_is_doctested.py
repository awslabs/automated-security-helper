def test_the_content_tree_and_the_nav_list_the_same_pages():
    tree, nav, unresolved = _site_pages()

    assert tree, (
        "docs/content holds no page, so every check on it would pass on nothing"
    )
    failures = reconcile_failures(tree, nav, unresolved)
    assert not failures, _message(
        "The docs content tree and docs/content/.nav.yml disagree:", failures
    )


def test_every_page_carries_a_doctest_mechanism_or_is_on_the_shrinking_allowlist():
    tree, _nav, _unresolved = _site_pages()
    allowlist = read_allowlist(ALLOWLIST.read_text(encoding="utf-8"))

    failures = ratchet_failures(tree, coverage_of(tree), allowlist)

    assert not failures, _message("The doctest ratchet is broken:", failures)


def test_the_allowlist_header_says_it_only_shrinks():
    header = [
        line
        for line in ALLOWLIST.read_text(encoding="utf-8").splitlines()
        if line.lstrip().startswith("#")
    ]

    assert RATCHET_SENTENCE in " ".join(header), (
        f"The comment at the top of {ALLOWLIST_REL} no longer says the file {RATCHET_SENTENCE}. "
        "That sentence is what tells a reader not to add a page to it."
    )


