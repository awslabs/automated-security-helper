"""No page of the docs site goes without a doctest mechanism, and no new one may.

The docs are held to the code by four mechanisms, each of which reaches only the pages
it names or finds. This test lists every page, computes which mechanisms reach it, and
fails on a page none reaches unless the page is on the ratchet allowlist
(``doctest_ratchet_allowlist.txt``, beside this file). The allowlist was seeded with
exactly the pages that had no mechanism when this test landed, and it may only shrink:
a page that gains a mechanism must be taken off it (the test fails until it is), and a
page added to the site has to be doctested from the start, because adding it to the
allowlist is the one thing a reviewer is told to refuse.

The same shape as ``tests/snapshot/config/test_snapshot_config_lint.py``'s
``test_fixtures_exercise_every_lint_category``: the set of things that need a pin is
read from the source of truth (here the docs tree and its navigation), not copied
into the test, so a new one without a pin fails.

What counts as a page. A markdown file under ``docs/content`` (``.md.template`` files
are the sources the version bump renders pages from, not pages). The tree and the
navigation (``docs/content/.nav.yml``, resolved by the same code ``scripts/docs_checks.py
check_nav`` runs, awesome-nav's own resolver) must list the same pages; a page in one
and not the other fails on its own, with the page named, before any coverage is read.

What counts as covered. A page is covered when at least one of these reaches it, and
each is read from the repository's files, not from a list kept here:

1. ``claims``: a module under ``tests/unit/docs`` pins the page's text. Read from the
   module's syntax tree: a function that calls ``assert_on_page``, ``_page_text`` or
   ``_page_section`` (in ``test_page_claims.py``), or a function that calls one that
   does, covers every page path it names, as a string in its body or its decorators or
   through a module-level constant it uses. A module that builds the page's path
   (``<root> / "plugins" / "aws.md"``, ``Path("docs/content/x.md")``) covers that page
   too. A page path in a function that pins nothing, or in a constant no pinning
   function uses, covers nothing.
2. ``examples``: the docs runner (``tests/integration/docs/test_docs_examples.py``)
   runs a block of the page, or compares an output sample on it. Decided by the
   runner's own selection, ``docs_runner.session_blocks`` over the page as
   ``docs_checks.parse_page`` reads it, so a page the runner skips is not counted.
3. ``twin``: a journey twin runs the page's steps through the docs runner, in a module
   under ``tests/integration/docs`` named ``test_*twin*.py`` or ``test_*journey*.py``
   (``test_local_tutorial_twin.py`` is the first). It covers the pages whose path it
   names, as a string or a path expression.
4. ``generated``: the page is written by a generator and the generator's ``--check`` is
   under the freshness test. The page opens with the banner
   ``scripts/_reference_docs.py`` writes (``Generated by scripts/<generator>.py``), the
   script exists, and ``tests/unit/test_generated_docs_freshness.py``'s
   ``REFERENCE_PAGES`` maps that generator to this page.

What does not count: a static check (the names, links, option tables and markers
``scripts/verify_docs_freshness.py`` runs). Those hold names and links to the code;
they do not run what a page says or pin a sentence about behavior, which is the
standard this gate ratchets toward. Limits of the readings above, so nobody believes
more than is here: "covered" means a mechanism reaches the page, not that every
claim on it is pinned (the journeys and the generation of the remaining pages are
what close that gap); a page path named in a claims function for another reason
counts as pinned; and a page whose only runnable block is trivial still counts as run.
"""

