def read_allowlist(text: str) -> list[str]:
    """The pages the allowlist names, in file order: every line that is not blank or a ``#``
    comment."""
    return [
        line.strip()
        for line in text.splitlines()
        if line.strip() and not line.lstrip().startswith("#")
    ]


def ratchet_failures(
    pages: set[str], coverage: Coverage, allowlist: list[str]
) -> list[str]:
    """Every way the pages, what covers them and the allowlist can disagree."""
    failures = []
    allowed = set(allowlist)
    for page in sorted(pages - set(coverage) - allowed):
        failures.append(
            f"docs/content/{page} has no doctest mechanism. Cover it: pin its sentences "
            "with assert_on_page in tests/unit/docs/test_page_claims.py, give its commands "
            "runnable blocks the docs runner executes, add a journey twin under "
            "tests/integration/docs, or generate it from code under a --check. A new page "
            f"does not go on {ALLOWLIST_REL}: that file may only shrink."
        )
    for page in sorted(allowed & set(coverage)):
        failures.append(
            f"{page} is on {ALLOWLIST_REL} but is covered now ({'; '.join(sorted(coverage[page]))}). "
            "Delete its line: the allowlist only shrinks, and a page left on it could lose its "
            "mechanism without this test noticing."
        )
    for page in sorted(allowed - pages):
        failures.append(
            f"{ALLOWLIST_REL} names {page}, which is not a page of the site. Delete its line "
            "(a page that was removed or renamed leaves nothing to allow)."
        )
    if allowlist != sorted(set(allowlist)):
        failures.append(
            f"{ALLOWLIST_REL} is not sorted, or names a page twice. Keep one page per line in "
            "sorted order, so a pull request that shrinks it shows only the lines it removes."
        )
    return failures


def _message(title: str, failures: list[str]) -> str:
    return title + "\n  - " + "\n  - ".join(failures)


