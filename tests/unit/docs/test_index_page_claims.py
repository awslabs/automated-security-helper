"""The index pages of the docs site say what is under them, and what they say is true.

Three pages of the site are hubs: ``reference/index.md`` (a table of the reference pages
and the generator of each), ``docs/plugins/alpha/index.md`` (the alpha
plugins that ship inside ASH) and ``personas/index.md`` (the three roles and the pages
for them). Each lists pages and names things in the code, and none had a mechanism that
reads the list, so a page added under a hub, or a generator renamed, left the hub
describing the site as it was. These tests read each hub's list from the page and hold
it to the tree and the code, in the two halves ``test_page_claims.py`` uses:
``assert_on_page`` pins the sentence, and the probe reads what makes it true.

What is pinned, and what is not:

- reference/index.md: the set of pages in the table is exactly the pages in
  ``docs/content/reference``; the generator each row names is a script in ``scripts/``,
  maps to that page in ``REFERENCE_PAGES`` of the freshness test, and is the generator
  the page's own banner names; a row that says "written by hand" is a page with no
  banner. Not pinned: the one-line description of what a page lists.
- alpha/index.md: the plugins in the list are the ``alpha`` pages beside it, the
  sentence after the list counts them, and each row that names a module
  (``ash_*_plugins``) names the package, under
  ``automated_security_helper/plugin_modules``, whose manifest owns that row's page.
  Not pinned: the submission guidelines, which are policy, and the tools each plugin
  runs.
- personas/index.md: the three roles in the table are the three role pages, and every
  link on the page names a page that exists. Not pinned: the argument about pace of
  iteration, which is prose.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

import pytest

from tests.unit.docs.test_page_claims import CONTENT, _spelled, assert_on_page
from tests.unit.test_generated_docs_freshness import REFERENCE_PAGES

pytestmark = pytest.mark.unit

REPO_ROOT = Path(__file__).resolve().parents[3]
REFERENCE_INDEX = "reference/index.md"
COMMUNITY_INDEX = "docs/plugins/alpha/index.md"
PERSONAS_INDEX = "personas/index.md"
PLUGIN_MODULES = REPO_ROOT / "automated_security_helper" / "plugin_modules"
BY_HAND = "written by hand"
BANNER = re.compile(r"Generated by (scripts/\S+?\.py)\b")

_ROW = re.compile(
    r"^\|\s*\[(?P<name>[^\]]+)\]\((?P<page>[^)#]+)\)\s*\|(?P<what>.*)\|(?P<how>[^|]*)\|\s*$",
    re.MULTILINE,
)
_LINK = re.compile(r"\]\(([^)\s]+)\)")


def page_text(page: str) -> str:
    return (CONTENT / page).read_text(encoding="utf-8")


def reference_rows(text: str) -> dict[str, str]:
    """Each row of the reference table: the page it links, and what its last cell says
    generates it (a ``scripts/...py`` path, or ``written by hand``)."""
    rows: dict[str, str] = {}
    for match in _ROW.finditer(text):
        how = match.group("how").strip().strip("`")
        rows[match.group("page")] = how
    return rows


def relative_pages(text: str) -> list[str]:
    """The page links of ``text`` that stay on the site (no scheme, no anchor-only)."""
    pages = []
    for target in _LINK.findall(text):
        if re.match(r"[a-z][a-z0-9+.-]*:", target) or target.startswith("#"):
            continue
        pages.append(target.partition("#")[0])
    return pages


def missing_links(page: str) -> list[str]:
    """The links of ``page`` that name no file under docs/content."""
    base = (CONTENT / page).parent
    return [
        target
        for target in relative_pages(page_text(page))
        if not (base / target).resolve().is_file()
    ]


# --------------------------------------------------------------------------- #
# The reader can fail: planted pages the parsers must read
# --------------------------------------------------------------------------- #


def test_the_table_reader_reads_a_generated_row_and_a_hand_written_row() -> None:
    planted = (
        "| Page | What it lists | Generated by |\n|---|---|---|\n"
        "| [CLI](cli.md) | every command | `scripts/generate_cli_docs.py` |\n"
        "| [Exit codes](exit-codes.md) | what each code means | written by hand |\n"
    )
    assert reference_rows(planted) == {
        "cli.md": "scripts/generate_cli_docs.py",
        "exit-codes.md": BY_HAND,
    }


def test_the_table_reader_reads_nothing_from_prose() -> None:
    assert reference_rows("See [CLI](cli.md) for the options.\n") == {}


def test_the_link_reader_skips_external_and_anchor_links() -> None:
    text = "[a](x.md#h) [b](https://example.com/y.md) [c](#top) [d](../z.md)"
    assert relative_pages(text) == ["x.md", "../z.md"]


