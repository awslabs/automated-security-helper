def test_the_reference_index_lists_every_reference_page() -> None:
    assert_on_page(
        REFERENCE_INDEX,
        "These pages list every command, setting and plugin ASH has.",
    )
    listed = set(reference_rows(page_text(REFERENCE_INDEX)))
    on_disk = {
        p.name for p in (CONTENT / "reference").glob("*.md") if p.name != "index.md"
    }
    assert listed == on_disk, (
        f"reference/index.md lists {sorted(listed - on_disk)} that is not a page, "
        f"and leaves out {sorted(on_disk - listed)}"
    )


def test_each_generator_the_reference_index_names_writes_the_page_beside_it() -> None:
    assert_on_page(
        REFERENCE_INDEX,
        "Each generated page names its generator at the top.",
    )
    rows = reference_rows(page_text(REFERENCE_INDEX))
    generated = {page: how for page, how in rows.items() if how != BY_HAND}
    assert generated, "the reference index names no generator"
    for page, script in generated.items():
        assert (REPO_ROOT / script).is_file(), f"{page}: {script} is not a script"
        assert REFERENCE_PAGES.get(Path(script).name) == page, (
            f"{page}: {script} is not the generator the freshness test maps to it "
            f"({REFERENCE_PAGES.get(Path(script).name)!r})"
        )
        banner = BANNER.search(page_text(f"reference/{page}"))
        assert banner and banner.group(1) == script, (
            f"reference/{page} names {banner and banner.group(1)!r} as its generator, "
            f"not {script}"
        )


def test_every_generated_reference_page_is_in_the_index_and_no_other_is() -> None:
    rows = reference_rows(page_text(REFERENCE_INDEX))
    by_hand = {page for page, how in rows.items() if how == BY_HAND}
    for page in sorted(by_hand):
        assert not BANNER.search(page_text(f"reference/{page}")), (
            f"reference/{page} is listed as {BY_HAND} but carries a generator banner"
        )
    assert set(REFERENCE_PAGES.values()) == set(rows) - by_hand


