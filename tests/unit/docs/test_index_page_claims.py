def test_the_personas_index_has_a_page_for_each_role() -> None:
    assert_on_page(
        PERSONAS_INDEX,
        "That one scan serves three jobs.",
    )
    text = page_text(PERSONAS_INDEX)
    roles = re.findall(
        r"^\| (Developer|Security reviewer|Security analyst) \|.*\[[^\]]+\]\(([^)]+)\) \|$",
        text,
        re.MULTILINE,
    )
    assert roles == [
        ("Developer", "developer.md"),
        ("Security reviewer", "security-reviewer.md"),
        ("Security analyst", "security-analyst.md"),
    ]
    on_disk = {p.name for p in (CONTENT / "personas").glob("*.md")}
    assert on_disk == {"index.md", "sdlc-aidlc.md"} | {page for _role, page in roles}


def test_the_personas_index_links_resolve() -> None:
    assert missing_links(PERSONAS_INDEX) == []


def test_the_link_checker_finds_a_link_to_nothing(tmp_path: Path, monkeypatch) -> None:
    """Control: the check above fails on a page that links to a file that is not there."""
    page = tmp_path / "p" / "index.md"
    page.parent.mkdir()
    page.write_text("[ok](index.md) and [gone](gone.md)\n", encoding="utf-8")
    monkeypatch.setattr(sys.modules[__name__], "CONTENT", tmp_path, raising=True)
    assert missing_links("p/index.md") == ["gone.md"]
