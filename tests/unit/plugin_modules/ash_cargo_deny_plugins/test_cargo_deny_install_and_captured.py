"""The module-local install pin, and the SARIF the scanner writes for a captured run.

``tests/test_data/scanners/cargo-deny/captured/`` holds what cargo-deny 0.21.0 wrote
(see its README). ``positive.sarif`` there is what ``scan()`` writes for the captured
positive run, regenerated by the test below, so the facets corpus gate reads output
the scanner produced from a real tool run, not a hand-built document.
"""

from __future__ import annotations

import json
import re
from pathlib import Path

import pytest

from automated_security_helper.core.exceptions import ToolNotProvisionableError
from automated_security_helper.plugin_modules.ash_cargo_deny_plugins import (
    cargo_deny_install as ci,
)

from .test_cargo_deny_scanner_behavior import FakeCargoDeny, _run, _scanner

pytestmark = pytest.mark.unit

CAPTURED = (
    Path(__file__).resolve().parents[3]
    / "test_data"
    / "scanners"
    / "cargo-deny"
    / "captured"
)
HEX64 = re.compile(r"[0-9a-f]{64}")


# ---------------------------------------------------------------------------
# Install pin
# ---------------------------------------------------------------------------


def test_every_asset_has_an_archive_digest_and_a_member_digest():
    assert set(ci.ASSETS.values()) == set(ci.ARCHIVE_SHA256) == set(ci.MEMBER_SHA256)
    for digest in [*ci.ARCHIVE_SHA256.values(), *ci.MEMBER_SHA256.values()]:
        assert HEX64.fullmatch(digest), digest
    assert len(set(ci.ARCHIVE_SHA256.values())) == len(ci.ARCHIVE_SHA256)
    assert len(set(ci.MEMBER_SHA256.values())) == len(ci.MEMBER_SHA256)


def test_asset_names_carry_the_pinned_version():
    for name in ci.ASSETS.values():
        assert name.startswith(f"cargo-deny-{ci.CARGO_DENY_VERSION}-"), name
        assert name.endswith(".tar.gz"), name


@pytest.mark.parametrize(
    "platform,arch,target,install_as",
    [
        ("linux", "amd64", "x86_64-unknown-linux-musl", "cargo-deny"),
        ("linux", "arm64", "aarch64-unknown-linux-musl", "cargo-deny"),
        ("darwin", "arm64", "aarch64-apple-darwin", "cargo-deny"),
        ("windows", "amd64", "x86_64-pc-windows-msvc", "cargo-deny.exe"),
    ],
)
def test_pinned_asset_resolves_a_published_pair(platform, arch, target, install_as):
    url, archive, member, name = ci.pinned_asset(platform, arch)
    assert url == (
        "https://github.com/EmbarkStudios/cargo-deny/releases/download/"
        f"{ci.CARGO_DENY_VERSION}/cargo-deny-{ci.CARGO_DENY_VERSION}-{target}.tar.gz"
    )
    assert HEX64.fullmatch(archive) and HEX64.fullmatch(member)
    assert name == install_as


@pytest.mark.parametrize(
    "pair", [("darwin", "amd64"), ("windows", "arm64"), ("freebsd", "amd64")]
)
def test_an_unpublished_pair_is_refused_by_name(pair):
    # cargo-deny 0.21.0 publishes no x86_64 macOS build and no arm64 Windows build.
    with pytest.raises(ToolNotProvisionableError, match=pair[0]):
        ci.pinned_asset(*pair)


def test_a_half_applied_bump_is_refused(monkeypatch):
    monkeypatch.setitem(
        ci.ASSETS,
        ("linux", "amd64"),
        "cargo-deny-99.0.0-x86_64-unknown-linux-musl.tar.gz",
    )
    with pytest.raises(ToolNotProvisionableError, match="half-applied"):
        ci.pinned_asset("linux", "amd64")


def test_the_linux_amd64_pin_is_the_asset_the_captures_name():
    # The captured README names the release asset the fixtures' runs came from.
    readme = (CAPTURED / "README.md").read_text(encoding="utf-8")
    name = ci.ASSETS[("linux", "amd64")]
    assert name in readme
    assert ci.ARCHIVE_SHA256[name] in readme


def test_the_install_table_builds_without_the_shared_pin_table(tmp_path, monkeypatch):
    monkeypatch.setenv("ASH_BIN_PATH", str(tmp_path / "bin"))
    table = ci.cargo_deny_install_commands()
    assert {(p, a) for p, arches in table.items() for a in arches} == set(ci.ASSETS)
    for arches in table.values():
        for commands in arches.values():
            (command,) = commands
            assert command.shell is False
            assert "install_cargo_deny" in " ".join(command.args)


def test_the_install_table_never_raises_without_a_bin_directory(monkeypatch):
    from automated_security_helper.utils import download_utils as du

    monkeypatch.setattr(du, "current_bin_path", lambda: None)
    table = ci.cargo_deny_install_commands()
    assert table["linux"]["amd64"], "a refusing command stands in"
    assert "install_cargo_deny" not in " ".join(table["linux"]["amd64"][0].args)


def test_an_offline_install_downloads_nothing(tmp_path, monkeypatch):
    from automated_security_helper.utils import download_utils as du

    def no_download(*args, **kwargs):
        raise AssertionError("an offline install must not download")

    monkeypatch.setattr(du, "is_offline_mode", lambda: True)
    monkeypatch.setattr(du, "download_file", no_download)
    with pytest.raises(ToolNotProvisionableError, match="offline"):
        ci.install_cargo_deny("linux", "amd64", tmp_path / "bin")
    assert not (tmp_path / "bin" / "cargo-deny").exists()


# ---------------------------------------------------------------------------
# The SARIF written for the captured run
# ---------------------------------------------------------------------------


def _single_project(tmp_path: Path) -> Path:
    source = tmp_path / "src"
    source.mkdir()
    (source / "Cargo.toml").write_text('[package]\nname = "root"\n')
    (source / "Cargo.lock").write_text("version = 4\n")
    return source


def test_the_committed_sarif_is_what_the_scanner_writes(tmp_path, monkeypatch):
    from automated_security_helper.plugin_modules.ash_cargo_deny_plugins import (
        cargo_deny_scanner as cds,
    )

    monkeypatch.setattr(cds, "find_executable", lambda cmd: f"/fake/bin/{cmd}")
    scanner = _scanner(_single_project(tmp_path), tmp_path)
    stderr = (CAPTURED / "positive.jsonl").read_text(encoding="utf-8")
    _run(scanner, FakeCargoDeny(stderr=stderr, exit_code=1), monkeypatch)
    written = Path(scanner.results_dir or scanner.context.output_dir) / "source"
    produced = json.loads((written / "cargo-deny.sarif").read_text(encoding="utf-8"))
    committed = json.loads((CAPTURED / "positive.sarif").read_text(encoding="utf-8"))
    assert committed == produced
    assert len(committed["runs"][0]["results"]) == 4
