"""Every CycloneDX model with an aliased field dumps by alias and loads by either
name, and a license list dumps as the dictionaries its readers expect.

Why this file exists
--------------------
The CycloneDX module is generated by datamodel-codegen and then hand-edited
(the "Not from the codegen" notes at its top). Two of those edits are per-model
settings that nothing checks across the module: ``serialize_by_alias=True`` on
every model that declares an aliased field (``bom-ref``, ``mime-type``), so a
nested model dumped on its own writes the alias and the document re-validates
under ``extra="forbid"``; and ``validate_by_name=True`` on the same models, so a
results file written before that fix, which stored a nested model under its
Python name ``bom_ref``, still loads. A model added or regenerated without the
pair would dump a document that refuses to load, or refuse the files ASH already
wrote, and only a later reader of some results file would notice. This walks the
module: the rule holds for every model, not for the ones someone remembered.

The SPDX reporter reads a component's licenses from the BOM's by-alias dump as
dictionaries keyed ``license`` / ``expression`` (``spdx_reporter._license_expressions``).
The typed license list keeps that dump shape; the last test pins it.
"""

from __future__ import annotations

import inspect

import pytest
from pydantic import BaseModel

from automated_security_helper.schemas import cyclonedx_bom_1_6_schema as cdx
from automated_security_helper.schemas.cyclonedx_bom_1_6_schema import CycloneDXReport

pytestmark = pytest.mark.unit


def _models_defined_in_the_module() -> list[type[BaseModel]]:
    return [
        obj
        for obj in vars(cdx).values()
        if inspect.isclass(obj)
        and issubclass(obj, BaseModel)
        and obj.__module__ == cdx.__name__
    ]


def _has_an_aliased_field(model: type[BaseModel]) -> bool:
    return any(
        field.alias is not None and field.alias != name
        for name, field in model.model_fields.items()
    )


def test_every_model_with_an_aliased_field_dumps_by_alias_and_loads_by_name():
    aliased = [m for m in _models_defined_in_the_module() if _has_an_aliased_field(m)]
    assert len(aliased) >= 20, [m.__name__ for m in aliased]
    missing = sorted(
        m.__name__
        for m in aliased
        if m.model_config.get("serialize_by_alias") is not True
        or m.model_config.get("validate_by_name") is not True
    )
    assert missing == [], missing


def test_control_the_walk_reaches_the_models_with_a_bom_ref():
    names = {
        m.__name__ for m in _models_defined_in_the_module() if _has_an_aliased_field(m)
    }
    assert {"Component", "Service", "Vulnerability"} <= names, sorted(names)


def test_a_results_file_written_with_nested_python_names_still_loads():
    """Before the alias fix a default dump wrote a nested ``bom_ref``; those
    results files are on disk and must keep loading. The reread dumps the alias."""
    stored = {
        "bomFormat": "CycloneDX",
        "specVersion": "1.6",
        "components": [{"type": "library", "name": "lib", "bom_ref": "pkg:lib@1.0"}],
    }
    report = CycloneDXReport.model_validate(stored)
    dumped = report.model_dump(exclude_none=True)
    assert dumped["components"][0]["bom-ref"] == "pkg:lib@1.0"
    assert "bom_ref" not in dumped["components"][0]


def test_control_an_unknown_key_is_still_refused():
    stored = {
        "bomFormat": "CycloneDX",
        "specVersion": "1.6",
        "components": [{"type": "library", "name": "lib", "bogus": 1}],
    }
    with pytest.raises(ValueError, match="bogus"):
        CycloneDXReport.model_validate(stored)


def test_the_license_list_dumps_as_the_dictionaries_its_readers_expect():
    licenses = [
        {"license": {"id": "Apache-2.0"}},
        {"license": {"name": "Acme Software License"}},
        {"expression": "MIT OR BSD-3-Clause", "acknowledgement": "concluded"},
    ]
    report = CycloneDXReport.model_validate(
        {
            "bomFormat": "CycloneDX",
            "specVersion": "1.6",
            "components": [{"type": "library", "name": "lib", "licenses": licenses}],
        }
    )
    dumped = report.model_dump(
        by_alias=True, exclude_unset=True, exclude_none=True, mode="json"
    )
    assert dumped["components"][0]["licenses"] == licenses
