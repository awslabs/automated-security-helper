def render_output_formats_table(rows: list[dict]) -> str:
    lines = [
        "| Format | File extension | Enabled by default | Primary use case | Standard |",
        "|--------|---------------|--------------------|-----------------|----------|",
    ]
    for r in rows:
        doc = REPORTER_DOCS[r["name"]]
        anchor = doc["anchor"]
        label = (
            f"[{doc['title']}](#{anchor}) (`{r['name']}`)"
            if anchor
            else f"{doc['title']} (`{r['name']}`)"
        )
        enabled = "Yes" if r["enabled"] else "No"
        lines.append(
            f"| {label} | `.{r['extension']}` | {enabled} | {doc['use_case']} | {doc['standard']} |"
        )
    return "\n".join(lines)


def render_output_formats_defaults(rows: list[dict]) -> str:
    on = [r["name"] for r in rows if r["enabled"]]
    off = [r["name"] for r in rows if not r["enabled"]]
    sentence = (
        f"Of the {len(rows)} built-in reporters, {len(on)} are enabled by default: "
        f"{_prose_list(on)}."
    )
    if off:
        sentence += (
            f" {_prose_list(off)} "
            f"{'is' if len(off) == 1 else 'are'} available but disabled by default."
        )
    return sentence


def render_plugin_reporters_table(rows: list[dict]) -> str:
    lines = [
        "| Reporter | Name | Format | Enabled by default | Use Case | Key Features |",
        "|----------|------|--------|--------------------|----------|--------------|",
    ]
    for r in rows:
        doc = REPORTER_DOCS[r["name"]]
        slug = doc["title"].lower().replace(" ", "-")
        enabled = "Yes" if r["enabled"] else "No"
        lines.append(
            f"| **[{doc['title']} Reporter](#{slug}-reporter)** | `{r['name']}` | "
            f"{doc['plugin_format']} | {enabled} | {doc['plugin_use_case']} | "
            f"{doc['plugin_features']} |"
        )
    return "\n".join(lines)


