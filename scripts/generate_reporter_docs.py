def _region_pattern(name: str) -> re.Pattern:
    # `(?:.*?\n)?` rather than `.*?\n` so that an empty region -- BEGIN
    # immediately followed by END, which is how a region is first introduced into
    # a page -- still matches and gets populated.
    return re.compile(
        re.escape(BEGIN.format(name=name))
        + r"\n(?:.*?\n)?"
        + re.escape(END.format(name=name)),
        re.DOTALL,
    )


def _replacement(name: str, body: str) -> str:
    return "\n".join([BEGIN.format(name=name), REGEN_NOTE, body, END.format(name=name)])


def apply_regions(check: bool) -> int:
    rows = registered_reporters()
    _check_editorial_coverage(rows)

    stale = []
    for rel_path, name, renderer in REGIONS:
        path = REPO_ROOT / rel_path
        original = path.read_text(encoding="utf-8")
        pattern = _region_pattern(name)
        if not pattern.search(original):
            raise SystemExit(
                f"ERROR: {rel_path} has no '{name}' generated region. Expected the "
                f"markers {BEGIN.format(name=name)} ... {END.format(name=name)}."
            )
        # A function replacement is used verbatim by re.sub -- no backslash or
        # group-reference escaping is applied to it. That matters because the
        # rendered tables contain URLs and backslashes would otherwise need
        # escaping here and unescaping on read.
        rendered = _replacement(name, renderer(rows))
        updated = pattern.sub(lambda _m: rendered, original, count=1)
        if updated == original:
            continue
        if check:
            stale.append((rel_path, name, original, updated))
        else:
            path.write_text(updated, encoding="utf-8")
            print(f"updated {rel_path} [{name}]", file=sys.stderr)

    if check and stale:
        print(
            "Reporter documentation is stale relative to the registered reporter set.\n"
            "Run: uv run python scripts/generate_reporter_docs.py\n",
            file=sys.stderr,
        )
        for rel_path, name, original, updated in stale:
            diff = difflib.unified_diff(
                original.splitlines(keepends=True),
                updated.splitlines(keepends=True),
                fromfile=f"{rel_path} (on disk)",
                tofile=f"{rel_path} (regenerated)",
                n=1,
            )
            print(f"--- region {name} ---", file=sys.stderr)
            sys.stderr.writelines(diff)
        return 1

    if check:
        print(
            f"Reporter documentation is up to date "
            f"({len(rows)} registered reporters, "
            f"{sum(1 for r in rows if r['enabled'])} enabled by default).",
            file=sys.stderr,
        )
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="Do not write. Exit non-zero with a diff if any region is stale.",
    )
    args = parser.parse_args()
    return apply_regions(check=args.check)


if __name__ == "__main__":
    sys.exit(main())
